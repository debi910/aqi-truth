-- Hourly layer, sub-index function and the audited AQI procedure.
CREATE TABLE AQ.HOURLY (
  STATION_ID INTEGER NOT NULL, PARAM VARCHAR(12) NOT NULL, HR TIMESTAMP(0) NOT NULL,  -- hour ending at HR
  N_RAW SMALLINT NOT NULL, N_OK SMALLINT NOT NULL,
  AVG_OK DOUBLE, AVG_ALL DOUBLE,
  FLAT SMALLINT NOT NULL DEFAULT 0, JUMP SMALLINT NOT NULL DEFAULT 0, IS_VALID SMALLINT NOT NULL,
  PRIMARY KEY (STATION_ID, PARAM, HR)
)@

-- CPCB sub-index: linear interpolation inside the breakpoint band, capped at 500.
CREATE OR REPLACE FUNCTION AQ.SUB_INDEX (P_PARAM VARCHAR(12), P_C DOUBLE)
 RETURNS SMALLINT LANGUAGE SQL DETERMINISTIC NO EXTERNAL ACTION READS SQL DATA
RETURN
 CASE WHEN P_C IS NULL THEN NULL WHEN P_C <= 0 THEN 0 ELSE
 (SELECT SMALLINT(ROUND(MIN(500, MIN(B.I_HI, B.I_LO + (P_C - B.BP_LO) * (B.I_HI - B.I_LO) / NULLIF(B.BP_HI - B.BP_LO, 0))), 0))
    FROM AQ.BREAKPOINT B
   WHERE B.PARAM = P_PARAM
     AND B.BP_LO = (SELECT MAX(BP_LO) FROM AQ.BREAKPOINT WHERE PARAM = P_PARAM AND BP_LO <= P_C)) END@

-- Build the hourly layer for hours ending in (P_FROM, P_TO]. The OpenAQ copy of CPCB data has
-- 15-minute rows that repeat the hourly value, stamped from the start of the hour (hh:00..hh:45),
-- so readings are bucketed by the hour they start in. Averages, data capture,
-- stuck-sensor runs (identical consecutive hourly values) and impossible jumps.
CREATE OR REPLACE PROCEDURE AQ.BUILD_HOURLY (IN P_FROM TIMESTAMP, IN P_TO TIMESTAMP)
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_MINQ SMALLINT;
  SELECT SMALLINT(NUM_VALUE) INTO V_MINQ FROM AQ.SETTING WHERE NAME = 'MIN_QUARTERS_PER_HOUR';
  DELETE FROM AQ.HOURLY WHERE HR > P_FROM AND HR <= P_TO;
  INSERT INTO AQ.HOURLY (STATION_ID, PARAM, HR, N_RAW, N_OK, AVG_OK, AVG_ALL, FLAT, JUMP, IS_VALID)
  WITH BASE AS (
    SELECT R.STATION_ID, R.PARAM, TRUNC(R.TS, 'HH') + 1 HOUR AS HR,
           COUNT(*) AS N_RAW,
           SUM(CASE WHEN R.VALUE BETWEEN P.MIN_V AND P.MAX_V THEN 1 ELSE 0 END) AS N_OK,
           AVG(CASE WHEN R.VALUE BETWEEN P.MIN_V AND P.MAX_V THEN R.VALUE END) AS AVG_OK,
           AVG(R.VALUE) AS AVG_ALL
      FROM AQ.READING R JOIN AQ.PLAUSIBLE P ON P.PARAM = R.PARAM
     WHERE R.TS >= P_FROM AND R.TS < P_TO
     GROUP BY R.STATION_ID, R.PARAM, TRUNC(R.TS, 'HH') + 1 HOUR),
  STEP AS (
    SELECT B.*, LAG(AVG_OK) OVER (PARTITION BY STATION_ID, PARAM ORDER BY HR) AS PREV_V,
           LAG(HR) OVER (PARTITION BY STATION_ID, PARAM ORDER BY HR) AS PREV_HR
      FROM BASE B WHERE N_OK >= V_MINQ),
  ISL AS (
    SELECT S.*, SUM(CASE WHEN PREV_HR = HR - 1 HOUR AND PREV_V = AVG_OK THEN 0 ELSE 1 END)
                  OVER (PARTITION BY STATION_ID, PARAM ORDER BY HR ROWS UNBOUNDED PRECEDING) AS ISLAND
      FROM STEP S),
  RUNS AS (
    SELECT I.*, COUNT(*) OVER (PARTITION BY STATION_ID, PARAM, ISLAND) AS RUN_LEN FROM ISL I),
  MARKED AS (
    SELECT R.STATION_ID, R.PARAM, R.HR,
           CASE WHEN R.RUN_LEN >= P.FLAT_HOURS THEN 1 ELSE 0 END AS FLAT,
           CASE WHEN R.PREV_HR = R.HR - 1 HOUR AND ABS(R.AVG_OK - R.PREV_V) > P.MAX_JUMP THEN 1 ELSE 0 END AS JUMP
      FROM RUNS R JOIN AQ.PLAUSIBLE P ON P.PARAM = R.PARAM)
  SELECT B.STATION_ID, B.PARAM, B.HR, B.N_RAW, B.N_OK, B.AVG_OK, B.AVG_ALL,
         COALESCE(M.FLAT, 0), COALESCE(M.JUMP, 0),
         CASE WHEN B.N_OK >= V_MINQ AND COALESCE(M.FLAT, 0) = 0 THEN 1 ELSE 0 END
    FROM BASE B LEFT JOIN MARKED M
      ON M.STATION_ID = B.STATION_ID AND M.PARAM = B.PARAM AND M.HR = B.HR
   WHERE B.HR > P_FROM AND B.HR <= P_TO;
END@

-- Audit one station-day (hours ending 01:00 .. 24:00 IST). Writes one VERDICT row and its
-- EVIDENCE rows, and returns the run id. Refuses (NOT_COMPUTABLE) instead of guessing.
CREATE OR REPLACE PROCEDURE AQ.COMPUTE_AQI_AUDITED (IN P_STATION INTEGER, IN P_DAY DATE, OUT P_RUN_ID BIGINT)
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_START TIMESTAMP; DECLARE V_END TIMESTAMP;
  DECLARE V_MIN24 SMALLINT; DECLARE V_MIN8 SMALLINT; DECLARE V_MINP SMALLINT;
  DECLARE V_NPARAMS SMALLINT DEFAULT 0; DECLARE V_HAS_PM SMALLINT DEFAULT 0;
  DECLARE V_AQI SMALLINT; DECLARE V_NAIVE SMALLINT; DECLARE V_PROM VARCHAR(12);
  DECLARE V_SUSPECT SMALLINT DEFAULT 0; DECLARE V_STATUS VARCHAR(16); DECLARE V_REASON VARCHAR(400);

  DECLARE GLOBAL TEMPORARY TABLE SESSION.PSTAT (
    PARAM VARCHAR(12), AVG_HOURS SMALLINT, VALID_H SMALLINT, BAD_RAW INTEGER, WORST_RAW DOUBLE,
    FLAT_H SMALLINT, JUMP_H SMALLINT, CONC DOUBLE, SUBIDX SMALLINT, NAIVE_CONC DOUBLE, NAIVE_IDX SMALLINT)
    WITH REPLACE ON COMMIT PRESERVE ROWS NOT LOGGED IN AQ_TEMP;

  SET V_START = TIMESTAMP(P_DAY);
  SET V_END = V_START + 1 DAY;
  SELECT SMALLINT(NUM_VALUE) INTO V_MIN24 FROM AQ.SETTING WHERE NAME = 'MIN_HOURS_24H';
  SELECT SMALLINT(NUM_VALUE) INTO V_MIN8 FROM AQ.SETTING WHERE NAME = 'MIN_HOURS_8H';
  SELECT SMALLINT(NUM_VALUE) INTO V_MINP FROM AQ.SETTING WHERE NAME = 'MIN_PARAMS';

  -- 24-hour pollutants: mean of valid hours, only if >= MIN_HOURS_24H valid hours.
  INSERT INTO SESSION.PSTAT
  SELECT P.PARAM, 24,
         COALESCE(SUM(H.IS_VALID), 0),
         COALESCE(SUM(H.N_RAW - H.N_OK), 0),
         (SELECT MIN(R.VALUE) FROM AQ.READING R WHERE R.STATION_ID = P_STATION AND R.PARAM = P.PARAM
             AND R.TS >= V_START AND R.TS < V_END AND R.VALUE NOT BETWEEN P.MIN_V AND P.MAX_V),
         COALESCE(SUM(H.FLAT), 0), COALESCE(SUM(H.JUMP), 0),
         CASE WHEN COALESCE(SUM(H.IS_VALID), 0) >= V_MIN24 THEN AVG(CASE WHEN H.IS_VALID = 1 THEN H.AVG_OK END) END,
         NULL, AVG(H.AVG_ALL), NULL
    FROM AQ.PLAUSIBLE P
    LEFT JOIN AQ.HOURLY H ON H.PARAM = P.PARAM AND H.STATION_ID = P_STATION AND H.HR > V_START AND H.HR <= V_END
   WHERE P.PARAM IN ('pm25', 'pm10', 'no2', 'so2')
   GROUP BY P.PARAM, P.MIN_V, P.MAX_V;

  -- 8-hour pollutants (O3, CO): maximum 8-hour running mean over windows ending in the day,
  -- each window needing >= MIN_HOURS_8H valid hours.
  INSERT INTO SESSION.PSTAT
  WITH W AS (
    SELECT E.PARAM, E.HR AS WEND,
           SUM(CASE WHEN H.IS_VALID = 1 THEN 1 ELSE 0 END) AS NV,
           AVG(CASE WHEN H.IS_VALID = 1 THEN H.AVG_OK END) AS M_OK,
           AVG(H.AVG_ALL) AS M_ALL
      FROM AQ.HOURLY E
      JOIN AQ.HOURLY H ON H.STATION_ID = E.STATION_ID AND H.PARAM = E.PARAM
                      AND H.HR > E.HR - 8 HOURS AND H.HR <= E.HR
     WHERE E.STATION_ID = P_STATION AND E.PARAM IN ('o3', 'co') AND E.HR > V_START AND E.HR <= V_END
     GROUP BY E.PARAM, E.HR),
  D AS (
    SELECT P.PARAM, P.MIN_V, P.MAX_V,
           COALESCE(SUM(H.IS_VALID), 0) AS VH, COALESCE(SUM(H.N_RAW - H.N_OK), 0) AS BAD,
           COALESCE(SUM(H.FLAT), 0) AS FL, COALESCE(SUM(H.JUMP), 0) AS JP
      FROM AQ.PLAUSIBLE P
      LEFT JOIN AQ.HOURLY H ON H.PARAM = P.PARAM AND H.STATION_ID = P_STATION AND H.HR > V_START AND H.HR <= V_END
     WHERE P.PARAM IN ('o3', 'co') GROUP BY P.PARAM, P.MIN_V, P.MAX_V)
  SELECT D.PARAM, 8, D.VH, D.BAD,
         (SELECT MIN(R.VALUE) FROM AQ.READING R WHERE R.STATION_ID = P_STATION AND R.PARAM = D.PARAM
             AND R.TS >= V_START AND R.TS < V_END AND R.VALUE NOT BETWEEN D.MIN_V AND D.MAX_V),
         D.FL, D.JP,
         (SELECT MAX(M_OK) FROM W WHERE W.PARAM = D.PARAM AND W.NV >= V_MIN8),
         NULL,
         (SELECT MAX(M_ALL) FROM W WHERE W.PARAM = D.PARAM),
         NULL
    FROM D;

  UPDATE SESSION.PSTAT SET SUBIDX = AQ.SUB_INDEX(PARAM, CONC), NAIVE_IDX = AQ.SUB_INDEX(PARAM, NAIVE_CONC);

  SELECT COUNT(*), COALESCE(MAX(CASE WHEN PARAM IN ('pm25', 'pm10') THEN 1 ELSE 0 END), 0), MAX(SUBIDX)
    INTO V_NPARAMS, V_HAS_PM, V_AQI
    FROM SESSION.PSTAT WHERE SUBIDX IS NOT NULL;
  SELECT MAX(NAIVE_IDX) INTO V_NAIVE FROM SESSION.PSTAT;
  SELECT COUNT(*) INTO V_SUSPECT FROM SESSION.PSTAT WHERE FLAT_H > 0 OR JUMP_H > 0 OR BAD_RAW > 0;

  IF V_NPARAMS >= V_MINP AND V_HAS_PM = 1 THEN
    SELECT PARAM INTO V_PROM FROM SESSION.PSTAT WHERE SUBIDX = V_AQI FETCH FIRST 1 ROW ONLY;
    SET V_STATUS = CASE WHEN V_SUSPECT > 0 THEN 'SUSPECT' ELSE 'VALID' END;
    SET V_REASON = 'AQI from ' || RTRIM(CHAR(V_NPARAMS)) || ' pollutants with enough valid data'
                   || CASE WHEN V_SUSPECT > 0 THEN '; some readings failed plausibility, stuck-sensor or jump checks and were excluded' ELSE '' END;
  ELSE
    SET V_AQI = NULL; SET V_PROM = NULL; SET V_STATUS = 'NOT_COMPUTABLE';
    SET V_REASON = 'Only ' || RTRIM(CHAR(V_NPARAMS)) || ' pollutant(s) had enough valid hours'
                   || CASE WHEN V_HAS_PM = 0 THEN ', and neither PM2.5 nor PM10 did' ELSE '' END
                   || '; CPCB needs at least ' || RTRIM(CHAR(V_MINP)) || ' including a PM';
  END IF;

  SELECT RUN_ID INTO P_RUN_ID FROM FINAL TABLE (
    INSERT INTO AQ.VERDICT (STATION_ID, DAY, STATUS, AQI, NAIVE_AQI, PROMINENT, VALID_PARAMS, REASON, DATA_AS_OF)
    VALUES (P_STATION, P_DAY, V_STATUS, V_AQI, V_NAIVE, V_PROM, V_NPARAMS, V_REASON, CURRENT TIMESTAMP));

  INSERT INTO AQ.EVIDENCE (RUN_ID, PARAM, CHECK_CODE, OBSERVED, RULE_REF, PASSED)
  SELECT P_RUN_ID, PARAM, 'COVERAGE',
         RTRIM(CHAR(VALID_H)) || ' of 24 hours valid', CASE AVG_HOURS WHEN 24 THEN 'CPCB-24H-16' ELSE 'CPCB-8H' END,
         CASE WHEN CONC IS NOT NULL THEN 1 ELSE 0 END FROM SESSION.PSTAT
  UNION ALL
  SELECT P_RUN_ID, PARAM, 'PLAUSIBLE',
         RTRIM(CHAR(BAD_RAW)) || ' readings outside physical range' || COALESCE(' (e.g. ' || VARCHAR(WORST_RAW) || ')', ''),
         'AQT-PLAUSIBLE', CASE WHEN BAD_RAW = 0 THEN 1 ELSE 0 END FROM SESSION.PSTAT
  UNION ALL
  SELECT P_RUN_ID, PARAM, 'STUCK', RTRIM(CHAR(FLAT_H)) || ' hours in identical-value runs', 'AQT-STUCK',
         CASE WHEN FLAT_H = 0 THEN 1 ELSE 0 END FROM SESSION.PSTAT
  UNION ALL
  SELECT P_RUN_ID, PARAM, 'JUMP', RTRIM(CHAR(JUMP_H)) || ' impossible hour-to-hour jumps', 'AQT-JUMP',
         CASE WHEN JUMP_H = 0 THEN 1 ELSE 0 END FROM SESSION.PSTAT
  UNION ALL
  SELECT P_RUN_ID, PARAM, 'SUBINDEX', COALESCE('C=' || VARCHAR(DECIMAL(CONC, 10, 2)) || ' -> ' || RTRIM(CHAR(SUBIDX)), 'not computed')
         || ' | naive ' || COALESCE(RTRIM(CHAR(NAIVE_IDX)), '-'), 'CPCB-BREAKPOINTS',
         CASE WHEN SUBIDX IS NOT NULL THEN 1 ELSE 0 END FROM SESSION.PSTAT
  UNION ALL
  SELECT P_RUN_ID, 'ALL', 'MIN_PARAMS', RTRIM(CHAR(V_NPARAMS)) || ' pollutants with sub-index, PM present=' || RTRIM(CHAR(V_HAS_PM)),
         'CPCB-3-POLLUTANTS', CASE WHEN V_STATUS <> 'NOT_COMPUTABLE' THEN 1 ELSE 0 END FROM SYSIBM.SYSDUMMY1;
END@

-- Audit every station for every day in [P_FROM, P_TO].
CREATE OR REPLACE PROCEDURE AQ.AUDIT_RANGE (IN P_FROM DATE, IN P_TO DATE)
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_DAY DATE; DECLARE V_RUN BIGINT;
  FOR S AS SELECT STATION_ID FROM AQ.STATION ORDER BY STATION_ID DO
    SET V_DAY = P_FROM;
    WHILE V_DAY <= P_TO DO
      CALL AQ.COMPUTE_AQI_AUDITED(S.STATION_ID, V_DAY, V_RUN);
      SET V_DAY = V_DAY + 1 DAY;
    END WHILE;

  END FOR;
END@
